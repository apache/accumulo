package org.apache.accumulo.gc;

import static org.apache.accumulo.core.Constants.BULK_PREFIX;
import static org.apache.accumulo.core.Constants.CLONE_PREFIX;
import static org.apache.accumulo.core.Constants.GENERATED_TABLET_DIRECTORY_PREFIX;
import static org.apache.accumulo.core.metadata.RootTable.ROOT_TABLET_DIR_NAME;
import static org.apache.accumulo.core.metadata.schema.MetadataSchema.TabletsSection.ServerColumnFamily.DEFAULT_TABLET_DIR_NAME;
import static org.apache.accumulo.server.init.FileSystemInitializer.TABLE_TABLETS_TABLET_DIR;

import java.net.URI;
import java.net.URISyntaxException;
import java.nio.file.Path;
import java.util.AbstractCollection;
import java.util.HashMap;
import java.util.Iterator;
import java.util.SortedMap;
import java.util.TreeMap;
import java.util.function.Consumer;

import org.apache.accumulo.core.gc.GcCandidate;
import org.apache.accumulo.core.gc.Reference;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;

import com.google.common.base.Preconditions;
import com.google.common.collect.Iterators;

/**
 * Code that supports efficient removal of references from a set of gc candidates.
 *
 * <p>
 * Internally this class uses relative paths to match references with candidates. This is done for
 * two reasons. First, it makes the normalization code easier to examine and verify. Normalization
 * is critical to matching, if done incorrectly it could lead to mismatches that cause referenced
 * files to be deleted. The second reason relative paths are used is to avoid problems with volume
 * replacements. If absolute paths were used, then more complex normalization and volume
 * replacements would need to be considered. Considering both of these increases the surface area
 * for mismatch bugs that could lead to deleting referenced files.
 *
 * <p>
 * Using relative paths is done with the following assumptions.
 * <ul>
 * <li>File names generated by accumulo are globally unique. If users are allowed to generate file
 * names for bulk import, then this may not be true.</li>
 * <li>Tablet directory names generated by accumulo are globally unique, except for the default
 * tablet in each table. If users are allowed to generate file names for bulk import, then accumulo
 * will enforce globally unique directory names in the bulk import fate operation.</li>
 * <li>All file paths generated by Accumulo will include a table id. If users are allowed to
 * generate file names for bulk import, then those paths would not include a table id.</li>
 * <li>Tablet directories either have a {@code t-} prefix or are named {@code default_tablet}</li>
 * <li>Bulk directories will have a {@code b-} prefix. If users are allowed to generate file names
 * for bulk import, it would be best for this code enforce another prefix like {@code be-}</li>
 * </ul>
 *
 * <p>
 * Putting the above assumptions together leads to the conclusion that the last two parts of a file
 * path are globally unique. For the case of a tables default tablet, its directory name is not
 * unique but all the files in the directory are. For the case of a user named bulk import path, its
 * file names may not be unique but its directory is. So for file matching only the last two path
 * elements are needed.
 *
 * <p>
 * When matching tablet directory deletion candidates, this code uses relative paths of the form
 * {@code /<table id>/<tablet dir>}. The table id is included to account for the default tablet
 * directory name not being unique across tables. When the table id is added, it makes the relative
 * path globally unique. Files in tablet directories are only created by Accumulo, so do not need to
 * consider matching user generated bulk paths.
 *
 * <p>
 * When matching bulk directories, it is assumed that bulk directory names are globally unique. User
 * created bulk paths may not have table id. Therefore, only the bulk directory name is used for
 * matching bulk directory candidates.
 *
 * <p>
 * When matching table deletion candidates, bulk and tablet directories are considered. User
 * generated bulk paths are not expected to have a table id, but if they did this could cause a
 * match that prevents deleting an empty table directory. As simple solution to this would be to
 * give user generated bulk directories a different prefix like {@code be-}, then those need not be
 * considered for matching.
 */
public class GcCandidates extends AbstractCollection<GcCandidate> {

  private static final Logger log = LoggerFactory.getLogger(GcCandidates.class);

  private final SortedMap<String,GcCandidate> fileCandidates = new TreeMap<>();
  private final HashMap<String,GcCandidate> tabletDirCandidates = new HashMap<>();
  private final HashMap<String,GcCandidate> bulkDirCandidates = new HashMap<>();
  private final HashMap<String,GcCandidate> tableDirCandidates = new HashMap<>();

  private record LastThree(String maybeATableId, String dir, String name) {
  }

  private LastThree lastThree(String strPath, int minPathLength) {
    return lastThree(strPath, true, minPathLength, Integer.MAX_VALUE);
  }

  private LastThree lastThree(String strPath, boolean expectScheme, int minPathLength,
      int maxPathLength) {
    URI uri = null;
    try {
      uri = new URI(strPath);
    } catch (URISyntaxException e) {
      throw new IllegalArgumentException(e);
    }

    if (expectScheme && uri.getScheme() == null) {
      throw new IllegalArgumentException("Missing scheme in URI " + strPath);
    }

    // TODO what about other parts of the URI?
    var path = Path.of(uri.getPath());

    int count = path.getNameCount();
    if (count < minPathLength) {
      throw new IllegalArgumentException("Path too short " + strPath);
    }

    if (count > maxPathLength) {
      throw new IllegalArgumentException("Path too long " + strPath);
    }

    if (count == 1) {
      return new LastThree(null, null, path.getName(count - 1).toString());
    } else if (count == 2) {
      return new LastThree(null, path.getName(count - 2).toString(),
          path.getName(count - 1).toString());
    } else if (count >= 3) {
      return new LastThree(path.getName(count - 3).toString(), path.getName(count - 2).toString(),
          path.getName(count - 1).toString());
    } else {
      throw new IllegalArgumentException("Bad path " + path);
    }
  }

  public GcCandidates(Iterable<GcCandidate> candidates) {
    candidates.forEach(candidate -> {
      try {
        switch (candidate.getType()) {
          case TABLET_FILE -> {
            var lastThree = lastThree(candidate.getPath(), 2);
            fileCandidates.put("/" + lastThree.dir + "/" + lastThree.name, candidate);
          }
          case TABLET_DIR -> {
            var lastThree = lastThree(candidate.getPath(), false, 2, 2);
            Preconditions.checkArgument(isTabletDir(lastThree.name), "Not a tablet dir %s",
                lastThree.name);
            tabletDirCandidates.put("/" + lastThree.dir + "/" + lastThree.name, candidate);
          }
          case BULK_DIR -> {
            var lastThree = lastThree(candidate.getPath(), 1);
            Preconditions.checkArgument(isBulkDir(lastThree.name), "Not a bulk dir %s",
                lastThree.name);
            bulkDirCandidates.put(lastThree.name, candidate);
          }
          case TABLE_DIR -> {
            var lastThree = lastThree(candidate.getPath(), false, 1, 1);
            tableDirCandidates.put(lastThree.name, candidate);
          }
        }
      } catch (IllegalArgumentException e) {
        log.warn("Ignoring invalid deletion candidate {} {}", candidate, e.getMessage());
      }
    });
  }

  @Override
  public Iterator<GcCandidate> iterator() {
    return Iterators.unmodifiableIterator(Iterators.concat(fileCandidates.values().iterator(),
        tabletDirCandidates.values().iterator(), bulkDirCandidates.values().iterator(),
        tableDirCandidates.values().iterator()));
  }

  public int removeBlip(String blip) {
    var lastThree = lastThree(blip, 2);

    String blipPrefix = "/" + lastThree.name + "/";

    bulkDirCandidates.remove(lastThree.name);

    var tailIter = fileCandidates.tailMap(blipPrefix).keySet().iterator();
    int removeCount = 0;
    while (tailIter.hasNext()) {
      if (tailIter.next().startsWith(blipPrefix)) {
        tailIter.remove();
        removeCount++;
      } else {
        break;
      }
    }

    return removeCount;
  }

  private static boolean isBulkDir(String dirName) {
    return dirName.startsWith(BULK_PREFIX);
  }

  private static boolean isTabletDir(String dirName) {
    return dirName.startsWith(GENERATED_TABLET_DIRECTORY_PREFIX) || dirName.startsWith(CLONE_PREFIX)
        || dirName.equals(DEFAULT_TABLET_DIR_NAME) || dirName.equals(ROOT_TABLET_DIR_NAME)
        || dirName.equals(TABLE_TABLETS_TABLET_DIR);
  }

  public void remove(Reference reference, Consumer<GcCandidate> removedConsumer) {

    Consumer<GcCandidate> nonNullConsumer = gcc -> {
      if (gcc != null) {
        removedConsumer.accept(gcc);
      }
    };

    if (reference.isDirectory()) {
      var lastThree = lastThree(reference.getMetadataPath(), false, 1, 1);
      nonNullConsumer
          .accept(tabletDirCandidates.remove("/" + reference.getTableId() + "/" + lastThree.name));
      nonNullConsumer.accept(tableDirCandidates.remove(reference.getTableId().toString()));
    } else {
      var lastThree = lastThree(reference.getMetadataPath(), 2);
      if (isTabletDir(lastThree.dir)) {
        Preconditions.checkArgument(lastThree.maybeATableId != null,
            "Path with tablet dir had no table id : %s", reference.getMetadataPath());
        nonNullConsumer.accept(
            tabletDirCandidates.remove("/" + lastThree.maybeATableId + "/" + lastThree.dir));
      } else if (isBulkDir(lastThree.dir)) {
        nonNullConsumer.accept(bulkDirCandidates.remove(lastThree.dir));
      } else {
        throw new IllegalArgumentException(
            "Unknown directory type in path: " + reference.getMetadataPath());
      }
      if (lastThree.maybeATableId != null) {
        nonNullConsumer.accept(tableDirCandidates.remove(lastThree.maybeATableId));
      }
      nonNullConsumer.accept(fileCandidates.remove("/" + lastThree.dir + "/" + lastThree.name));
    }
  }

  @Override
  public int size() {
    return tabletDirCandidates.size() + fileCandidates.size() + bulkDirCandidates.size()
        + tableDirCandidates.size();
  }
}
